# JSX parsing helpers


def matching_brace(text: str, start: int) -> int:
    depth, quote, i = 0, None, start
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "\"'`":
            quote = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError(f"unbalanced braces in {text!r}")


def eval_expression(expr: str):
    try:
        return json.loads(expr)
    except json.JSONDecodeError:
        return expr


def parse_attrs(raw: str) -> dict:
    attrs, i, n = {}, 0, len(raw)
    name_re = re.compile(r"[\w.:-]+")
    while i < n:
        if raw[i].isspace():
            i += 1
            continue
        m = name_re.match(raw, i)
        if not m:
            i += 1
            continue
        name, i = m.group(0), m.end()
        if i < n and raw[i] == "=":
            i += 1
            if raw[i] in "\"'":
                end = raw.index(raw[i], i + 1)
                value = html.unescape(raw[i + 1:end])
                i = end + 1
            elif raw[i] == "{":
                end = matching_brace(raw, i)
                value = eval_expression(raw[i + 1:end].strip())
                i = end + 1
            else:
                m = re.compile(r"\S+").match(raw, i)
                value, i = m.group(0), m.end()
        else:
            value = True
        attrs[name] = value
    return attrs


class Tag:
    def __init__(self, end, name, attrs, closing, self_closing):
        self.end, self.name, self.attrs = end, name, attrs
        self.closing, self.self_closing = closing, self_closing


def scan_tag(text: str, pos: int = 0):
    """Parse the JSX tag at text[pos]. Returns None when the tag is not closed in text."""
    m = TAG_START.match(text, pos)
    if not m:
        return None
    i, quote, depth = m.end(), None, 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == quote:
                quote = None
        elif depth and c in "\"'`":
            quote = c
        elif not depth and c in "\"'":
            quote = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        elif c == ">" and depth == 0:
            raw = text[m.end():i].rstrip()
            self_closing = raw.endswith("/")
            if self_closing:
                raw = raw[:-1]
            return Tag(i + 1, m.group(2), parse_attrs(raw), bool(m.group(1)), self_closing)
        i += 1
    return None


def split_frontmatter(text: str):
    meta = {}
    if not text.startswith("---\n"):
        return meta, text
    end = text.index("\n---", 4)
    for line in text[4:end].splitlines():
        m = re.match(r"^([\w-]+):\s*(.*)$", line)
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            meta[m.group(1)] = value
    return meta, text[end + 4:].lstrip("\n")


def slug(text: str) -> str:
    text = re.sub(r"[^\w\s-]", "", text.lower()).strip()
    return re.sub(r"[\s]+", "-", text)


def kebab(name: str) -> str:
    return re.sub(r"[A-Z]", lambda m: "-" + m.group(0).lower(), name)


def snake(name: str) -> str:
    return re.sub(r"[A-Z]", lambda m: "_" + m.group(0).lower(), name)


