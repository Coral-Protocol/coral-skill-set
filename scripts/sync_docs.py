class SchemaRenderer:
    def __init__(self, spec):
        self.schemas = spec.get("components", {}).get("schemas", {})
        self.order: list[str] = []
        self.queue: list[str] = []

    def ref(self, name: str) -> str:
        if name not in self.order and name not in self.queue:
            self.queue.append(name)
        return name

    def type_of(self, s: dict, indent: int) -> str:
        if not isinstance(s, dict) or not s:
            return "unknown"
        if "$ref" in s:
            return self.ref(s["$ref"].rsplit("/", 1)[-1])
        for key in ("anyOf", "oneOf"):
            if key in s:
                variants = [self.type_of(v, indent + 1) for v in s[key]]
                return self.union(variants, indent)
        if "allOf" in s:
            return " & ".join(self.type_of(v, indent) for v in s["allOf"])
        if "enum" in s:
            return " | ".join(json.dumps(v) for v in s["enum"])
        t = s.get("type")
        nullable = s.get("nullable") or (isinstance(t, list) and "null" in t)
        if isinstance(t, list):
            t = next((x for x in t if x != "null"), None)
        if t == "array":
            inner = self.type_of(s.get("items", {}), indent)
            result = f"Array<{inner}>" if re.search(r"[\s|{]", inner) else f"{inner}[]"
        elif t == "object" or "properties" in s:
            if s.get("properties"):
                result = self.object(s, indent)
            elif isinstance(s.get("additionalProperties"), dict):
                result = f"Record<string, {self.type_of(s['additionalProperties'], indent)}>"
            else:
                result = "object"
        elif t in ("string", "boolean", "integer", "number"):
            result = t
            if s.get("format") in ("int64", "int32", "double", "float", "date-time", "uri"):
                result += f" /* {s['format']} */"
        else:
            result = "unknown"
        return result + " | null" if nullable else result

    def union(self, variants, indent):
        if all("\n" not in v for v in variants) and sum(len(v) for v in variants) < 90:
            return " | ".join(variants)
        pad = "  " * indent
        return "".join(f"\n{pad}  | {v}" for v in variants)

    def object(self, s, indent):
        required = set(s.get("required", []))
        props = s["properties"]
        compact = all("description" not in p for p in props.values())
        if compact:
            fields = [f"{k}{'' if k in required else '?'}: {self.type_of(v, indent + 1)}" for k, v in props.items()]
            line = "{ " + "; ".join(fields) + " }"
            if "\n" not in line and len(line) < 100:
                return line
        pad = "  " * (indent + 1)
        out = ["{"]
        for key, value in props.items():
            if value.get("description"):
                out.append(f"{pad}// {' '.join(value['description'].split())}")
            out.append(f"{pad}{key}{'' if key in required else '?'}: {self.type_of(value, indent + 1)}")
        out.append("  " * indent + "}")
        return "\n".join(out)

    def render_all(self) -> list[str]:
        out = []
        while self.queue:
            name = self.queue.pop(0)
            self.order.append(name)
            schema = self.schemas.get(name)
            out += [f"## {name}", ""]
            if schema is None:
                out += ["Not defined in api_v1.json.", ""]
                continue
            if schema.get("description"):
                out += [" ".join(schema["description"].split()), ""]
            out += ["```ts", f"type {name} = {self.type_of(schema, 0)}", "```", ""]
        return out


def endpoint_anchor(op: dict) -> str:
    return slug(op.get("summary") or op.get("operationId", ""))


def render_endpoints(spec, nav_items, renderer: SchemaRenderer):
    out = ["# API reference: endpoints", "",
           "Rendered from the docs' `api_v1.json` in the order of the docs' API Reference tab.",
           "Schemas are in [schemas.md](schemas.md). The raw OpenAPI document is [api_v1.json](api_v1.json).",
           "The running server's own schema at `/api_v1.json` is authoritative for that server.", ""]

    def schema_link(content):
        schema = (content or {}).get("application/json", {}).get("schema")
        if not schema:
            return None
        rendered = renderer.type_of(schema, 0)
        if "$ref" in schema:
            return f"[`{rendered}`](schemas.md#{rendered.lower()})"
        return f"`{' '.join(rendered.split())}`"

    def walk(items, level):
        for item in items:
            if isinstance(item, dict):
                if item.get("group") == "Models":
                    continue
                out.extend(["#" * level + " " + item["group"], ""])
                walk(item.get("pages", []), min(level + 1, 6))
                continue
            if " " not in item:
                continue
            method, path = item.split(" ", 1)
            op = spec["paths"].get(path, {}).get(method.lower())
            if op is None:
                out.extend([f"{'#' * level} {method} {path}", "", "Missing from api_v1.json.", ""])
                continue
            out.extend([f"{'#' * level} {op.get('summary', path)}", "", f"`{method} {path}`", ""])
            if op.get("description"):
                out.extend([" ".join(op["description"].split()), ""])
            for param in op.get("parameters", []):
                schema = param.get("schema", {})
                required = ", required" if param.get("required") else ""
                desc = f": {' '.join(param['description'].split())}" if param.get("description") else ""
                out.append(f"- {param.get('in', 'param')} `{param['name']}` "
                           f"({renderer.type_of(schema, 0)}{required}){desc}")
            body = op.get("requestBody")
            if body:
                link = schema_link(body.get("content"))
                required = "required" if body.get("required") else "optional"
                desc = f". {' '.join(body['description'].split())}" if body.get("description") else ""
                out.append(f"- Request body ({required}): {link}{desc}")
            for code, response in op.get("responses", {}).items():
                link = schema_link(response.get("content"))
                desc = " ".join(response.get("description", "").split())
                out.append(f"- Response {code}: {desc}" + (f", {link}" if link else ""))
            schemes = sorted({k for sec in op.get("security", []) for k in sec})
            if schemes:
                out.append(f"- Auth: bearer `{'`, `'.join(schemes)}`")
            out.append("")

    walk(nav_items, 2)
    return out


