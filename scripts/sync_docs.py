class Converter:
    def __init__(self, site, page: str):
        self.site, self.page = site, page
        self.out: list[str] = []
        self.buf: list[tuple[bool, str]] = []
        self.stack: list[dict] = []
        self.root_heading = 1
        self.tree = None
        self.tree_depth = 0
        self.anchors: dict[str, str] = {}
        self.dropping = False
        self.in_comment = False

    # output helpers ---------------------------------------------------------------------

    def prefix(self) -> str:
        parts = []
        for frame in self.stack:
            if frame["kind"] == "callout":
                parts.append("> ")
            elif frame["kind"] == "indent":
                parts.append("  ")
        return "".join(parts)

    def emit(self, lines, separate=True):
        if separate and self.out and self.out[-1].rstrip(" >") != "":
            self.out.append(self.prefix().rstrip())
        prefix = self.prefix()
        for line in lines:
            self.out.append((prefix + line).rstrip() if line else prefix.rstrip())

    def flush(self):
        if not self.buf:
            return
        dedented = textwrap.dedent("\n".join(line for _, line in self.buf)).split("\n")
        lines = []
        for (is_code, _), line in zip(self.buf, dedented):
            lines.append(line if is_code else self.inline(line))
        self.buf = []
        lines = collapse_blank_lines(lines)
        while lines and not lines[0].strip():
            lines.pop(0)
        while lines and not lines[-1].strip():
            lines.pop()
        if not lines:
            return
        if not any(f["kind"] == "headed" for f in self.stack):
            fence = None
            for line in lines:
                if FENCE.match(line.strip()):
                    fence = None if fence else True
                elif not fence:
                    m = re.match(r"^(#{1,6})\s", line)
                    if m:
                        self.root_heading = len(m.group(1))
        self.emit(lines)

    # inline transforms -------------------------------------------------------------------

    def inline(self, line: str) -> str:
        parts = re.split(r"(`[^`\n]*`)", line)
        for i in range(0, len(parts), 2):
            parts[i] = self.inline_text(parts[i])
        return "".join(parts).rstrip()

    def inline_text(self, text: str) -> str:
        text = re.sub(r"\{/\*.*?\*/\}", "", text)
        text = re.sub(r"""\{\s*(["'])\s*\1\s*\}""", " ", text)
        text = re.sub(r"<Icon\b[^>]*/>", "", text)
        text = re.sub(r"<br\s*/?>", "", text)
        text = re.sub(r"<Badge\b[^>]*>(.*?)</Badge>", lambda m: f"**{m.group(1).strip()}**", text)
        text = re.sub(r"<code>(.*?)</code>", r"`\1`", text)
        text = re.sub(r"<Tooltip\b[^>]*>(.*?)</Tooltip>", r"\1", text)
        text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
        text = re.sub(r"\[([^\]]*?)\s+\]\(", r"[\1](", text)
        for m in re.finditer(r"</?([A-Z][\w.]*)\b[^>]*>", text):
            self.site.warn(f"{self.page}: dropped inline tag <{m.group(1)}>")
        text = re.sub(r"</?([A-Z][\w.]*)\b[^>]*>", "", text)
        text = re.sub(r"\]\(([^)\s]+)\)", lambda m: "](" + self.site.link(self.page, m.group(1)) + ")", text)
        return html.unescape(text)

    # block tags --------------------------------------------------------------------------

    def heading_level(self) -> int:
        for frame in reversed(self.stack):
            if frame["kind"] == "headed":
                return min(frame["level"] + 1, 6)
        return min(self.root_heading + 1, 6)

    def pop(self, kind):
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["kind"] == kind:
                del self.stack[i:]
                return
        self.site.warn(f"{self.page}: unmatched closing tag for {kind}")

    def handle(self, tag: Tag):
        name, attrs = tag.name, tag.attrs
        opening = not tag.closing and not tag.self_closing
        if name in TSX_RENDERERS:
            self.flush()
            self.emit(TSX_RENDERERS[name](attrs))
            return
        if name in DROPPED:
            self.dropping = opening
            return
        if self.tree is not None and name in ("Tree.Folder", "Tree.File", "Tree"):
            if name == "Tree" and tag.closing:
                block = ["```text"] + ["  " * d + entry for d, entry in self.tree] + ["```"]
                self.tree = None
                self.emit(block)
            elif name == "Tree.Folder":
                if tag.closing:
                    self.tree_depth -= 1
                else:
                    self.tree.append((self.tree_depth, f"{attrs.get('name')}/"))
                    if opening:
                        self.tree_depth += 1
            elif name == "Tree.File" and not tag.closing:
                self.tree.append((self.tree_depth, str(attrs.get("name"))))
            return
        self.flush()
        if name == "Tree":
            if opening:
                self.tree, self.tree_depth = [], 0
            return
        if name in CALLOUTS:
            if opening:
                self.emit([f"> **{CALLOUTS[name]}:**"])
                self.stack.append({"kind": "callout"})
            elif tag.closing:
                self.pop("callout")
                self.out.append("")
            return
        if name == "Steps":
            if opening:
                self.stack.append({"kind": "steps", "count": 0})
            elif tag.closing:
                self.pop("steps")
            return
        if name in HEADED:
            if tag.closing:
                self.pop("headed")
                return
            title = str(attrs.get("title") or attrs.get("label") or attrs.get("description") or "")
            if name == "Step":
                steps = next((f for f in reversed(self.stack) if f["kind"] == "steps"), None)
                if steps is not None:
                    steps["count"] += 1
                    title = f"Step {steps['count']}: {title}"
            level = self.heading_level()
            heading = self.inline_text(title)
            if attrs.get("id"):
                self.anchors[str(attrs["id"])] = slug(heading)
            self.emit(["#" * level + " " + heading])
            if opening:
                self.stack.append({"kind": "headed", "level": level})
            return
        if name == "Tab":
            if opening:
                self.emit([f"**{attrs.get('title', 'Tab')}**"])
                self.stack.append({"kind": "tab"})
            elif tag.closing:
                self.pop("tab")
            return
        if name == "Card":
            if tag.closing:
                self.pop("indent")
                return
            title = str(attrs.get("title", ""))
            href = attrs.get("href")
            label = f"[{title}]({self.site.link(self.page, href)})" if href else title
            self.emit([f"- **{label}**"])
            if opening:
                self.stack.append({"kind": "indent"})
            return
        if name in FIELDS:
            if tag.closing:
                self.pop("indent")
                return
            field = next((attrs[k] for k in ("body", "path", "query", "header", "name") if k in attrs), "?")
            details = [str(attrs["type"])] if "type" in attrs else []
            if attrs.get("required"):
                details.append("required")
            if "default" in attrs:
                details.append(f"default `{attrs['default']}`")
            suffix = f" ({', '.join(details)})" if details else ""
            self.emit([f"- `{field}`{suffix}"])
            if opening:
                self.stack.append({"kind": "indent"})
            return
        if name in ("iframe", "video"):
            src = attrs.get("src")
            if src and not tag.closing:
                src = f"{DOCS_URL}{src}" if str(src).startswith("/") else src
                self.emit([f"[Video]({src})"])
            return
        if name == "img" or name in TRANSPARENT:
            return
        self.site.warn(f"{self.page}: treated unknown block tag <{name}> as transparent")

    # driver ------------------------------------------------------------------------------

    def is_block(self, name: str) -> bool:
        return name in BLOCK_TAGS or name in TSX_RENDERERS or (name[0].isupper() and name not in INLINE_TAGS)

    def convert(self, text: str) -> list[str]:
        lines = text.split("\n")
        i, fence = 0, None
        while i < len(lines):
            line = lines[i]
            i += 1
            stripped = line.strip()
            if fence:
                self.buf.append((True, line))
                if stripped.startswith(fence) and set(stripped) == {fence[0]}:
                    fence = None
                continue
            if self.in_comment:
                if "*/}" in line:
                    self.in_comment = False
                    line = line.split("*/}", 1)[1]
                else:
                    continue
            if "{/*" in line and "*/}" not in line.split("{/*", 1)[1]:
                self.in_comment = True
                line = line.split("{/*", 1)[0]
            if not self.dropping and self.tree is None:
                m = FENCE.match(line.strip())
                if m:
                    fence = m.group(1)
                    self.buf.append((True, line))
                    continue
            while True:
                if self.dropping:
                    m = re.search(r"</TODO\s*>", line)
                    if not m:
                        break
                    self.dropping = False
                    line = line[m.end():]
                    continue
                s = line.lstrip()
                if s.startswith("<"):
                    tag = scan_tag(s)
                    start = TAG_START.match(s)
                    while tag is None and start and self.is_block(start.group(2)) and i < len(lines):
                        s += "\n" + lines[i]
                        i += 1
                        tag = scan_tag(s)
                    if tag and self.is_block(tag.name):
                        self.handle(tag)
                        line = s[tag.end:]
                        if not line.strip():
                            break
                        continue
                m = re.search(r"</([A-Za-z][\w.]*)\s*>\s*$", line)
                if m and m.group(1) in BLOCK_TAGS and m.group(1) not in INLINE_TAGS:
                    before = line[:m.start()]
                    if before.strip():
                        self.add(before)
                    self.handle(Tag(0, m.group(1), {}, True, False))
                    break
                self.add(line)
                break
        self.flush()
        out = self.out
        for anchor, target in self.anchors.items():
            out = [line.replace(f"](#{anchor})", f"](#{target})") for line in out]
        return collapse_blank_lines(out)

    def add(self, line: str):
        if self.tree is not None:
            return
        self.buf.append((False, line))


def collapse_blank_lines(lines):
    result = []
    for line in lines:
        if line.strip(" >") == "" and result and result[-1].strip(" >") == "" and line == result[-1]:
            continue
        result.append(line)
    return result


