class Site:
    def __init__(self, docs_root: Path):
        self.root = docs_root
        self.config = json.loads((docs_root / "docs.json").read_text())
        self.redirects = {r["source"].strip("/"): r["destination"].strip("/")
                          for r in self.config.get("redirects", [])}
        self.spec = json.loads((docs_root / "api_v1.json").read_text())
        self.pages: dict[str, dict] = {}
        self.endpoint_slugs: dict[str, str] = {}
        self.aliased = defaultdict(set)
        self.unresolved = defaultdict(set)
        self.hidden = defaultdict(set)
        self.warnings: list[str] = []
        for path, methods in self.spec.get("paths", {}).items():
            for op in methods.values():
                for tag in op.get("tags", []):
                    self.endpoint_slugs[f"api-reference/{tag}/{endpoint_anchor(op)}"] = endpoint_anchor(op)

    def warn(self, message: str):
        if message not in self.warnings:
            self.warnings.append(message)

    def tabs(self):
        return self.config["navigation"]["tabs"]

    def collect_pages(self):
        listed = []

        def walk(items):
            for item in items:
                if isinstance(item, str):
                    listed.append(item.strip("/"))
                else:
                    if item.get("root"):
                        listed.append(item["root"].strip("/"))
                    walk(item.get("pages", []))

        for tab in self.tabs():
            walk(tab.get("groups", []))
            if "openapi" not in tab:
                walk(tab.get("pages", []))
        for page in listed:
            if page in EXCLUDED_PAGES or page.startswith("api-reference/"):
                continue
            source = self.root / f"{page}.mdx"
            if not source.exists():
                self.warn(f"navigation lists {page} but {source.name} does not exist")
                continue
            meta, _ = split_frontmatter(source.read_text())
            self.pages[page] = meta
        return listed

    def link(self, page: str, href) -> str:
        href = str(href)
        target = href
        if target.startswith(DOCS_URL):
            target = target[len(DOCS_URL):] or "/"
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
            return href
        if not target.startswith("/"):
            target = str((Path("/" + page).parent / target))
        path, _, anchor = target.strip("/").partition("#")
        original = path
        path = self.redirects.get(path, path)
        if path in LINK_ALIASES:
            self.aliased[f"/{original} -> /{LINK_ALIASES[path]}"].add(page)
            path = LINK_ALIASES[path]
        suffix = f"#{anchor}" if anchor else ""
        if path in self.pages:
            return relative(page, f"{path}.md") + suffix
        if path.startswith("api-reference/models/"):
            return relative(page, "api-reference/schemas.md") + "#" + path.rsplit("/", 1)[-1].lower()
        if path in self.endpoint_slugs:
            return relative(page, "api-reference/endpoints.md") + "#" + self.endpoint_slugs[path]
        if path.startswith("api-reference"):
            return relative(page, "api-reference/endpoints.md")
        if (self.root / f"{path}.mdx").exists():
            self.hidden[f"/{path}"].add(page)
        else:
            self.unresolved[f"/{original}"].add(page)
        return f"{DOCS_URL}/{original}{suffix}"

    def render_page(self, page: str) -> str:
        source = self.root / f"{page}.mdx"
        meta, body = split_frontmatter(source.read_text())
        body = expand_snippets(body, source, self.root)
        lines = Converter(self, page).convert(body)
        title = meta.get("title") or page
        header = [f"# {title}", ""]
        description = meta.get("description")
        if description and description.strip().lower() != title.strip().lower():
            header += [description, ""]
        header += [f"Source: {DOCS_URL}/{page}", ""]
        return "\n".join(header + lines).rstrip() + "\n"

    def render_index(self) -> str:
        commit = git(self.root, "rev-parse", "--short", "HEAD") or "unknown"
        date = git(self.root, "log", "-1", "--format=%cs")
        dirty = " plus uncommitted changes" if git(self.root, "status", "--porcelain") else ""
        out = ["# Coral docs mirror", "",
               f"Plain-Markdown mirror of {DOCS_URL}. {MARKER} from docs commit `{commit}` ({date}){dirty}.",
               "Do not edit these files by hand. Fix the docs upstream, then re-run the script.", "",
               "Treat the docs as the authority on intent and concepts. Version notes in the prose can lag the",
               "server, so confirm exact request and response shapes against the target server's `/api_v1.json`.", ""]

        def entry(page, depth):
            meta = self.pages[page]
            title = meta.get("sidebarTitle") or meta.get("title") or page
            desc = meta.get("description", "")
            desc = f": {desc}" if desc and desc.lower() != title.lower() else ""
            return "  " * depth + f"- [{title}]({page}.md){desc}"

        def walk(items, depth, top=False):
            for item in items:
                if isinstance(item, str):
                    page = item.strip("/")
                    if page in self.pages:
                        out.append(entry(page, depth))
                    elif page.startswith("api-reference/models/"):
                        name = page.rsplit("/", 1)[-1]
                        out.append("  " * depth + f"- [{name}](api-reference/schemas.md#{name.lower()})")
                    continue
                root = (item.get("root") or "").strip("/")
                if top:
                    out.extend(["", f"### {item['group']}", ""])
                    if root in self.pages:
                        out.append(entry(root, 0))
                    walk(item.get("pages", []), 0)
                else:
                    label = f"[{item['group']}]({root}.md)" if root in self.pages else item["group"]
                    out.append("  " * depth + f"- **{label}**")
                    walk(item.get("pages", []), depth + 1)

        for tab in self.tabs():
            out.extend(["", f"## {tab['tab']}"])
            if "openapi" in tab:
                out.extend(["",
                            f"Generated from Coral Server {self.spec.get('info', {}).get('version', 'unknown')}.", "",
                            "- [Endpoints](api-reference/endpoints.md): every endpoint in the API Reference tab",
                            "- [Schemas](api-reference/schemas.md): request and response types as compact TypeScript",
                            "- [api_v1.json](api-reference/api_v1.json): the raw OpenAPI document the docs render"])
            else:
                walk(tab.get("groups", []), 0, top=True)
        return "\n".join(collapse_blank_lines(out)).strip() + "\n"

    def report(self, listed):
        """Turn coverage and link problems found during the build into warnings."""
        all_pages = sorted(str(p.relative_to(self.root))[:-4] for p in self.root.rglob("*.mdx")
                           if "node_modules" not in p.parts)
        for page in all_pages:
            if page not in listed and not page.startswith(("snippets/", "api-reference/")):
                self.warn(f"{page} is not in the docs navigation, so it is not mirrored")
        for link, pages in sorted(self.aliased.items()):
            self.warn(f"link {link} points at a moved page (in {', '.join(sorted(pages))})")
        for link, pages in sorted(self.hidden.items()):
            self.warn(f"link {link} points at a page hidden from navigation (in {', '.join(sorted(pages))})")
        for link, pages in sorted(self.unresolved.items()):
            self.warn(f"link {link} has no target in the docs repository (in {', '.join(sorted(pages))})")

    def build(self, out_dir: Path):
        listed = self.collect_pages()
        files = {}
        for page in self.pages:
            files[f"{page}.md"] = self.render_page(page)
        api_tab = next(t for t in self.tabs() if "openapi" in t)
        renderer = SchemaRenderer(self.spec)
        files["api-reference/endpoints.md"] = "\n".join(render_endpoints(self.spec, api_tab["pages"], renderer)).rstrip() + "\n"
        for item in api_tab["pages"]:
            if isinstance(item, dict) and item.get("group") == "Models":
                for model in item.get("pages", []):
                    renderer.ref(model.rsplit("/", 1)[-1])
        schemas = ["# API reference: schemas", "",
                   "Compact TypeScript-style rendering of the docs' `api_v1.json`, in breadth-first order from the endpoints.",
                   "A `?` marks an optional property. Comments carry the schema descriptions.", ""]
        files["api-reference/schemas.md"] = "\n".join(schemas + renderer.render_all()).rstrip() + "\n"
        files["INDEX.md"] = self.render_index()
        self.report(listed)
        for rel, content in files.items():
            content = "\n".join(line.rstrip() for line in content.split("\n"))
            target = out_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        shutil.copyfile(self.root / "api_v1.json", out_dir / "api-reference" / "api_v1.json")


def relative(from_page: str, to_file: str) -> str:
    from_dir = Path(from_page).parent
    up = len(from_dir.parts)
    return "/".join([".."] * up + [to_file]) if up else to_file


def git(repo: Path, *args) -> str:
    try:
        return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""


def trees_equal(a: Path, b: Path) -> list[str]:
    diffs = []
    cmp = filecmp.dircmp(a, b)

    def walk(c, prefix=""):
        diffs.extend(prefix + n for n in c.left_only + c.right_only)
        _, mismatch, errors = filecmp.cmpfiles(c.left, c.right, c.common_files, shallow=False)
        diffs.extend(prefix + n for n in mismatch + errors)
        for name, sub in c.subdirs.items():
            walk(sub, prefix + name + "/")

    walk(cmp)
    return diffs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--docs-repo", type=Path, default=DEFAULT_DOCS_REPO,
                        help=f"path to a checkout of Coral-Protocol/Docs (default: {DEFAULT_DOCS_REPO})")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="mirror directory to write")
    parser.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh build")
    args = parser.parse_args()
    docs_root = args.docs_repo.resolve()
    if not (docs_root / "docs.json").exists():
        parser.error(f"{docs_root} is not a Mintlify docs checkout (no docs.json)")

    with tempfile.TemporaryDirectory() as tmp:
        site = Site(docs_root)
        site.build(Path(tmp))
        for warning in site.warnings:
            print(f"warning: {warning}", file=sys.stderr)
        out = args.out.resolve()
        if args.check:
            diffs = trees_equal(Path(tmp), out) if out.exists() else ["(mirror directory missing)"]
            if diffs:
                print("Docs mirror is stale:\n  " + "\n  ".join(diffs), file=sys.stderr)
                return 1
            print("Docs mirror is up to date.")
            return 0
        if out.exists():
            index = out / "INDEX.md"
            if any(out.iterdir()) and not (index.exists() and MARKER in index.read_text()):
                parser.error(f"refusing to replace {out}: it exists and is not a generated mirror")
            shutil.rmtree(out)
        shutil.copytree(tmp, out)
        print(f"Wrote {len(site.pages)} pages to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
