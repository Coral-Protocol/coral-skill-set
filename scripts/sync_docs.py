TSX_RENDERERS = {}


def tsx(name):
    def register(fn):
        TSX_RENDERERS[name] = fn
        return fn
    return register


@tsx("ServerConfigSingle")
def render_server_config_single(attrs):
    table, config, example = attrs["table"], attrs["config"], attrs["example"]
    return [f"- Command line: `--{table}.{kebab(config)}={example}`",
            f"- Config file: `{table}.{snake(config)} = {example}`"]


@tsx("ServerConfigList")
def render_server_config_list(attrs):
    table, config, examples = attrs["table"], attrs["config"], attrs["examples"]
    flags = " ".join(f"--{table}.{kebab(config)}={e}" for e in examples)
    return [f"- Command line: `{flags}`",
            f"- Config file: `{table}.{snake(config)} = [{', '.join(examples)}]`"]


def expand_snippets(text: str, file_path: Path, docs_root: Path) -> str:
    """Inline MDX snippet imports and drop import/export statements outside code blocks."""
    imports, lines, fence, skipping_export = {}, [], None, False
    for line in text.split("\n"):
        stripped = line.strip()
        if fence:
            lines.append(line)
            if stripped.startswith(fence) and set(stripped) == {fence[0]}:
                fence = None
            continue
        if skipping_export:
            skipping_export = stripped not in ("};", "}")
            continue
        m = FENCE.match(stripped)
        if m:
            fence = m.group(1)
            lines.append(line)
            continue
        m = re.match(r"""^import\s+(\w+)\s+from\s+["'](.+?\.mdx)["'];?$""", stripped)
        if m:
            target = m.group(2)
            base = docs_root if target.startswith("/") else file_path.parent
            imports[m.group(1)] = (base / target.lstrip("/")).resolve()
            continue
        if re.match(r"""^import\s+\{[^}]*\}\s+from\s+["'].+?\.tsx["'];?$""", stripped):
            continue
        if stripped.startswith("export const "):
            skipping_export = not stripped.endswith(";")
            continue
        lines.append(line)
    text = "\n".join(lines)
    for name, path in imports.items():
        def replace(m, path=path):
            body = expand_snippets(path.read_text(), path, docs_root)
            for key, value in parse_attrs(m.group(1)).items():
                body = body.replace("{" + key + "}", str(value))
            return "\n" + body.strip("\n") + "\n"
        text = re.sub(r"<" + name + r"\b(.*?)/>", replace, text, flags=re.S)
    return text


